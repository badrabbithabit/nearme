#!/usr/bin/env python3
"""Build the static bundle that GitHub Pages hosts.

Pages serves files, not processes, so the web app's /api/* calls have nothing to
answer them. This flattens ONE snapshot of the same pipeline server.py uses into
`nearme.json` at the site root, and the app then filters client-side (bbox,
severity, radius) instead of asking the server to do it.

Refuses to produce a bundle when a feed comes back empty, so a flaky upstream can
never publish an empty map over a working one.

    python build_site.py                     # -> ./_site
    python build_site.py --out _site --layers chp_incidents,lane_closures
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "src"))

from nearme.api import LEVEL_COLORS, events_as_geojson, load_events  # noqa: E402
from nearme.fetch import Fetcher  # noqa: E402
from nearme.query import DEFAULT_LAYERS  # noqa: E402

ROOT = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.join(ROOT, "web")

# The Pages snapshot is regenerated by a scheduled workflow, not polled live;
# the browser should not hammer GitHub's CDN harder than that.
STATIC_POLL_SECONDS = 300

ATTRIBUTION = (
    "Incidents courtesy CHP; lane closures courtesy Caltrans, via quickmap.dot.ca.gov"
)


def build(layers, cache_dir):
    fetcher = Fetcher(cache_dir=cache_dir, min_refresh_seconds=0)
    events, statuses = load_events(fetcher, layers, force=True)

    per_layer: dict[str, int] = {}
    for e in events:
        per_layer[e.layer] = per_layer.get(e.layer, 0) + 1

    # Guard: an empty feed means the upstream (or our parser) broke. Publish
    # nothing rather than a blank map.
    empty = [layer for layer in layers if not per_layer.get(layer)]
    if empty:
        raise SystemExit(
            "REFUSING to build - no events parsed for: "
            + ", ".join(empty)
            + "\n  "
            + "\n  ".join(statuses)
        )

    fc = events_as_geojson(events)  # statewide: no bbox, no center
    fc["nearme"] = {
        "mode": "static",
        "generated_at": int(time.time()),
        "total": len(fc["features"]),
        "per_layer": per_layer,
        "statuses": statuses,
        "levels": LEVEL_COLORS,
        "refresh_seconds": STATIC_POLL_SECONDS,
        "attribution": ATTRIBUTION,
    }
    return fc


def main() -> int:
    ap = argparse.ArgumentParser(description="build the static (Pages) bundle")
    ap.add_argument("--out", default=os.path.join(ROOT, "_site"))
    ap.add_argument("--layers", default=",".join(DEFAULT_LAYERS))
    ap.add_argument("--cache-dir", default=os.path.join(ROOT, ".cache"))
    args = ap.parse_args()

    out = os.path.abspath(args.out)
    fc = build(tuple(args.layers.split(",")), args.cache_dir)

    os.makedirs(out, exist_ok=True)
    for name in os.listdir(WEB):
        src = os.path.join(WEB, name)
        if os.path.isdir(src):
            shutil.copytree(src, os.path.join(out, name), dirs_exist_ok=True)
        else:
            shutil.copy2(src, os.path.join(out, name))

    blob = json.dumps(fc, separators=(",", ":"), ensure_ascii=False)
    with open(os.path.join(out, "nearme.json"), "w", encoding="utf-8") as f:
        f.write(blob)

    print(f"  {len(fc['features'])} features -> {os.path.join(out, 'nearme.json')} "
          f"({len(blob) / 1024:.0f} KiB)")
    for line in fc["nearme"]["statuses"]:
        print(f"    {line}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
